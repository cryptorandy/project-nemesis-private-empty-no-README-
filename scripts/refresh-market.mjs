#!/usr/bin/env node
/**
 * Bake+refresh path for Project Nemesis market truth.
 *
 * Hosted Cursor apps cannot call Robinhood MCP from the browser.
 * Agents (or a local operator with MCP) pull:
 *   get_accounts → get_portfolio / get_equity_positions /
 *   get_equity_quotes / get_crypto_quotes / get_watchlist_items
 * then write `public/data/market.json`, `public/data/book.json` (positions+portfolio),
 * and optionally sync TS fallback.
 *
 * Usage:
 *   node scripts/refresh-market.mjs              # validate + print status of existing JSON
 *   node scripts/refresh-market.mjs --from-stdin  # pipe a MarketSnapshot JSON object
 *   node scripts/refresh-market.mjs --write-ts    # also rewrite src/data/rh-snapshot.ts
 *
 * This script never places orders.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const jsonPath = join(root, 'public/data/market.json')
const bookPath = join(root, 'public/data/book.json')
const tsPath = join(root, 'src/data/rh-snapshot.ts')

const args = new Set(process.argv.slice(2))

function fail(msg) {
  console.error(`[refresh-market] ${msg}`)
  process.exit(1)
}

function validate(snap) {
  if (!snap || typeof snap !== 'object') fail('snapshot must be an object')
  if (typeof snap.asOf !== 'string') fail('asOf required (ISO-8601)')
  if (!snap.portfolio) fail('portfolio required')
  for (const key of ['indices', 'board', 'crypto', 'positions', 'newsCrawl']) {
    if (!Array.isArray(snap[key])) fail(`${key} must be an array`)
  }
  return snap
}

async function readStdin() {
  const chunks = []
  for await (const chunk of process.stdin) chunks.push(chunk)
  return Buffer.concat(chunks).toString('utf8')
}

function writeTsFallback(snap) {
  const q = (row) => {
    const note = row.note ? `, note: ${JSON.stringify(row.note)}` : ''
    return `  { symbol: ${JSON.stringify(row.symbol)}, name: ${JSON.stringify(row.name)}, price: ${row.price}, prevClose: ${row.prevClose}, changePct: ${row.changePct}, source: 'rh'${note} },`
  }
  const p = (row) =>
    `  {\n    symbol: ${JSON.stringify(row.symbol)},\n    qty: ${row.qty},\n    avgCost: ${row.avgCost},\n    mark: ${row.mark},\n    value: ${row.value},\n    pnl: ${row.pnl},\n    pnlPct: ${row.pnlPct},\n  },`

  const body = `/**
 * Robinhood MCP snapshot baked for the hosted app (TypeScript fallback).
 *
 * Gap: Cursor-published static apps cannot call Robinhood MCP at runtime.
 * Agents refresh \`public/data/market.json\` (+ this file) via MCP; the UI polls
 * that JSON and falls back here if the poll fails. No place-order calls.
 *
 * Captured: ${snap.asOf} via get_equity_quotes / get_crypto_quotes /
 * get_portfolio / get_equity_positions / get_watchlist_items
 * Account: MCP ${snap.accountMasked ?? snap.portfolio.accountMasked} (agentic)
 *
 * AUTO-GENERATED by scripts/refresh-market.mjs — prefer editing market.json.
 */

export type RhQuote = {
  symbol: string
  name: string
  price: number
  prevClose: number
  changePct: number
  source: 'rh'
  note?: string
}

export type RhPosition = {
  symbol: string
  qty: number
  avgCost: number
  mark: number
  value: number
  pnl: number
  pnlPct: number
}

export type RhPortfolio = {
  totalValue: number
  equityValue: number
  optionsValue: number
  cash: number
  buyingPower: number
  accountMasked: string
}

export const RH_AS_OF = ${JSON.stringify(snap.asOf)}
export const RH_SOURCE_NOTE = ${JSON.stringify(snap.sourceNote ?? 'RH MCP bake · hosted app polls /data/market.json')}

export const RH_PORTFOLIO: RhPortfolio = ${JSON.stringify(snap.portfolio, null, 2)}

export const RH_INDICES: RhQuote[] = [
${snap.indices.map(q).join('\n')}
]

export const RH_BOARD: RhQuote[] = [
${snap.board.map(q).join('\n')}
]

export const RH_CRYPTO: RhQuote[] = [
${snap.crypto.map(q).join('\n')}
]

export const RH_POSITIONS: RhPosition[] = [
${snap.positions.map(p).join('\n')}
]

export const RH_WATCHLIST = ${JSON.stringify(
    snap.watchlist ?? { id: '', name: 'Watch', symbols: [] },
    null,
    2,
  )}

/** Options heat stub — MCP options quotes not wired into board yet */
export const OPTIONS_HEAT_STUB = [
  { underlying: 'NVDA', side: 'Call', strike: 170, expiry: '11/21', iv: '42%', heat: 'elevated' },
  { underlying: 'TSLA', side: 'Call', strike: 410, expiry: '11/21', iv: '51%', heat: 'hot' },
  { underlying: 'SPY', side: 'Put', strike: 750, expiry: '11/14', iv: '14%', heat: 'quiet' },
  { underlying: 'AMD', side: 'Call', strike: 600, expiry: '12/19', iv: '48%', heat: 'watch' },
  { underlying: 'META', side: 'Put', strike: 610, expiry: '11/28', iv: '29%', heat: 'quiet' },
]

export const NEWS_CRAWL = ${JSON.stringify(snap.newsCrawl, null, 2)}
`
  writeFileSync(tsPath, body)
  console.log(`[refresh-market] wrote ${tsPath}`)
}

async function main() {
  let snap

  if (args.has('--from-stdin')) {
    const text = await readStdin()
    snap = validate(JSON.parse(text))
    writeFileSync(jsonPath, `${JSON.stringify(snap, null, 2)}\n`)
    console.log(`[refresh-market] wrote ${jsonPath} asOf=${snap.asOf}`)
  } else {
    if (!existsSync(jsonPath)) fail(`missing ${jsonPath}`)
    snap = validate(JSON.parse(readFileSync(jsonPath, 'utf8')))
    console.log(
      `[refresh-market] ok asOf=${snap.asOf} board=${snap.board.length} crypto=${snap.crypto.length} positions=${snap.positions.length} degraded=${Boolean(snap.degraded)}`,
    )
  }

  const book = {
    schemaVersion: snap.schemaVersion ?? 1,
    asOf: snap.asOf,
    refreshedBy: snap.refreshedBy ?? 'agent-mcp',
    accountMasked: snap.accountMasked ?? snap.portfolio.accountMasked,
    sourceNote:
      snap.bookSourceNote ??
      'RH MCP book · prefer over market.json for positions/portfolio',
    degraded: Boolean(snap.degraded),
    portfolio: snap.portfolio,
    positions: snap.positions,
  }
  writeFileSync(bookPath, `${JSON.stringify(book, null, 2)}\n`)
  console.log(
    `[refresh-market] wrote ${bookPath} positions=${book.positions.length}`,
  )

  if (args.has('--write-ts')) {
    writeTsFallback(snap)
  }

  console.log(
    '[refresh-market] hosted limit: browser cannot call RH MCP; redeploy or push refreshed market.json + book.json for new marks',
  )
}

main().catch((err) => fail(err?.message ?? String(err)))
